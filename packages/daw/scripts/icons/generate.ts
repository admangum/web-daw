import fs from "node:fs/promises";
import path from "node:path";
import { optimize, type CustomPlugin } from "svgo";
import { transform, type ConfigPlugin } from "@svgr/core";
import jsxModule from "@svgr/plugin-jsx";
import prettier from "prettier";

const ICONS_DIR = path.resolve(import.meta.dirname, "../../src/ui/icons");
export const SVG_DIR = path.join(ICONS_DIR, "svg");
const COMPONENTS_DIR = path.join(ICONS_DIR, "components");
const INDEX_FILE = path.join(ICONS_DIR, "index.ts");
const HEADER = "// AUTO-GENERATED by scripts/icons/generate.ts. Do not edit.\n";

// CJS package: depending on the loader, the plugin is either the module or its `default`.
const jsx = ((jsxModule as { default?: unknown }).default ?? jsxModule) as ConfigPlugin;

const pascal = (s: string) =>
  s
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");

/** Strips hardcoded size and paint; keeps viewBox, `fill="none"`/`stroke="none"` on children. */
const cleanIcon: CustomPlugin = {
  name: "cleanIcon",
  fn: () => {
    let viewBox: number[] = [];
    return {
      element: {
        enter(node, parent) {
          const { attributes } = node;
          if (node.name === "svg") {
            delete attributes.width;
            delete attributes.height;
            delete attributes.fill;
            delete attributes.stroke;
            viewBox = (attributes.viewBox ?? "").split(/\s+/).map(Number);
            return;
          }
          // Figma exports sometimes include a frame outline covering the whole viewBox.
          const [, , vw, vh] = viewBox;
          if (
            node.name === "rect" &&
            vw &&
            vh &&
            Number(attributes.width) >= vw - 1 &&
            Number(attributes.height) >= vh - 1 &&
            (!attributes.fill || attributes.fill === "none")
          ) {
            parent.children = parent.children.filter((c) => c !== node);
            return;
          }
          for (const key of ["fill", "stroke"]) {
            if (key in attributes && attributes[key] !== "none") delete attributes[key];
          }
        },
      },
    };
  },
};

async function format(file: string, source: string, parser: "typescript" | "html") {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(source, { ...config, parser: parser === "html" ? "html" : "typescript" });
}

async function writeIfChanged(file: string, content: string) {
  const existing = await fs.readFile(file, "utf8").catch(() => null);
  if (existing === content) return false;
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
  return true;
}

async function listSvgs(dir: string): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  const nested = await Promise.all(
    entries.map(async (e) => {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) return listSvgs(full);
      return e.name.endsWith(".svg") ? [full] : [];
    })
  );
  return nested.flat().sort();
}

/** Directory tree of icon names, used to build barrels. */
interface Node {
  icons: Set<string>;
  dirs: Map<string, Node>;
}

function barrelSource(node: Node, prefix: string) {
  const lines = [...node.icons].sort().map((n) => `export { default as ${n} } from "./${n}";`);
  for (const dir of [...node.dirs.keys()].sort()) {
    lines.push(`export * as ${pascal(dir)} from "./${prefix}${dir}";`);
  }
  return HEADER + lines.join("\n") + "\n";
}

export async function syncIcons() {
  const svgs = await listSvgs(SVG_DIR);
  const expected = new Set<string>();
  const root: Node = { icons: new Set(), dirs: new Map() };
  const barrels: [string, string][] = [];

  for (const svgFile of svgs) {
    const rel = path.relative(SVG_DIR, svgFile);
    const parts = rel.split(path.sep);
    const name = pascal(path.basename(rel, ".svg"));
    const dirParts = parts.slice(0, -1);

    // 1. Clean the SVG in place.
    const original = await fs.readFile(svgFile, "utf8");
    const cleaned =
      optimize(original, {
        plugins: [cleanIcon],
        js2svg: { pretty: true, indent: 2 },
      }).data.trim() + "\n";
    if (cleaned !== original) await fs.writeFile(svgFile, cleaned);

    // 2. Generate the component.
    const outFile = path.join(COMPONENTS_DIR, ...dirParts, `${name}.tsx`);
    const code = await transform(
      cleaned,
      { plugins: [jsx], typescript: true, jsxRuntime: "automatic", expandProps: "end" },
      { componentName: name }
    );
    await writeIfChanged(outFile, HEADER + (await format(outFile, code, "typescript")));
    expected.add(outFile);

    let node = root;
    for (const d of dirParts) {
      if (!node.dirs.has(d)) node.dirs.set(d, { icons: new Set(), dirs: new Map() });
      node = node.dirs.get(d)!;
    }
    node.icons.add(name);
  }

  // 3. Barrels: components/<dir>/index.ts per directory, then icons/index.ts.
  const walk = (node: Node, dir: string) => {
    for (const [d, child] of node.dirs) {
      const childDir = path.join(dir, d);
      barrels.push([path.join(childDir, "index.ts"), barrelSource(child, "")]);
      walk(child, childDir);
    }
  };
  walk(root, COMPONENTS_DIR);
  for (const [file] of barrels) expected.add(file);
  for (const [file, src] of barrels)
    await writeIfChanged(file, await format(file, src, "typescript"));

  const rootLines = [...root.icons]
    .sort()
    .map((n) => `export { default as ${n} } from "./components/${n}";`);
  for (const d of [...root.dirs.keys()].sort()) {
    rootLines.push(`export * as ${pascal(d)} from "./components/${d}";`);
  }
  await writeIfChanged(
    INDEX_FILE,
    await format(INDEX_FILE, HEADER + rootLines.join("\n") + "\n", "typescript")
  );

  // 4. Prune generated files (and empty dirs) with no matching SVG.
  await prune(COMPONENTS_DIR, expected);
}

async function prune(dir: string, expected: Set<string>): Promise<boolean> {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  let empty = true;
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (await prune(full, expected)) await fs.rmdir(full);
      else empty = false;
    } else if (!expected.has(full) && (await fs.readFile(full, "utf8")).startsWith(HEADER)) {
      await fs.rm(full);
    } else {
      empty = false;
    }
  }
  return empty;
}
